-- =============================================================================
-- 0003：表格配置增加「界面配置」JSON
--
-- 背景：
--   「表格配置」页面里原来只能配字段、搜索、按钮，
--   表格多高、新增/编辑弹框多大只能写死在组件里，一张表一个样就得改代码。
--   现在把这两项抽成一段 JSON 存进 config：
--     { "table": { "height": 700 }, "form": { "dialog": { "width": 1200, "height": 960 } } }
--
-- 注意：
--   1. 允许为 NULL。为 NULL 表示「没配过」，前端用内置默认值兜底，
--      这样以后再往 JSON 里加字段，不需要给历史数据做任何迁移。
--   2. 只做加法（ADD COLUMN），不动历史数据、不删任何列。
-- =============================================================================

ALTER TABLE "sys_table_config"
    ADD COLUMN "config" JSONB;
